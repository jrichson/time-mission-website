/**
 * Emits src/data/site/astro-rendered-output-files.json from Astro page modules.
 * Humans maintain routes.json and src/pages; this manifest is machine-derived for sync + checks.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { publicLocationsForProfile, resolveSiteProfile } from '../config/site-profiles.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const pagesDir = path.join(root, 'src', 'pages');
const routesPath = path.join(root, 'src', 'data', 'routes.json');
const locationsPath = path.join(root, 'data', 'locations.json');
const outPath = path.join(root, 'src', 'data', 'site', 'astro-rendered-output-files.json');
const routeManifestPath = path.join(root, 'functions', '_shared', 'location-route-manifest.mjs');
const specialStaticOutputFiles = new Set([
  '404.html',
  'group-form-thank-you/jotform.html',
]);

function walkAstroFiles(dir, base = '') {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = path.join(base, ent.name).replace(/\\/g, '/');
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      out.push(...walkAstroFiles(full, rel));
    } else if (ent.name.endsWith('.astro')) {
      out.push(rel);
    }
  }
  return out;
}

function astroRelToOutputHtml(rel) {
  const parts = rel.split('/');
  const file = parts.pop();
  const stem = file.replace(/\.astro$/, '');
  const segs = [...parts, stem === 'index' ? 'index.html' : `${stem}.html`].filter(Boolean);
  return segs.join('/');
}

/** e.g. c/[slug].astro — emits paths at build time, not registrable as a single routes.json row */
function hasDynamicSegment(relPath) {
  return relPath.split('/').some((segment) => segment.includes('[') && segment.includes(']'));
}

const astroRels = walkAstroFiles(pagesDir);
const dynamicLandingModules = astroRels.filter(hasDynamicSegment).sort();
const staticAstroRels = astroRels.filter((rel) => !hasDynamicSegment(rel));

const registry = JSON.parse(fs.readFileSync(routesPath, 'utf8'));
const locationsDocument = JSON.parse(fs.readFileSync(locationsPath, 'utf8'));
const siteProfile = resolveSiteProfile(process.env);
const profiledLocationsDocument = {
  ...locationsDocument,
  locations: publicLocationsForProfile(locationsDocument.locations, siteProfile),
};
const routeOutputs = new Set(
  (registry.routes || []).map((r) => String(r.outputFile || '').replace(/^\//, '')),
);

function isPipedriveFormUrl(value) {
  return typeof value === 'string' && value.includes('webforms.pipedrive.com');
}

function isOnSiteGroupInquiryUrl(value) {
  return typeof value === 'string'
    && /^\/groups\/inquire\/[a-z0-9-]+\/[a-z0-9-]+\/?$/.test(value);
}

function groupFormThankYouOutputFiles(locationsDocument) {
  const locations = Array.isArray(locationsDocument.locations) ? locationsDocument.locations : [];
  const files = [];
  for (const location of locations) {
    const slug = String(location?.slug || location?.id || '').trim();
    if (!slug) continue;
    const formUrls = location.groupFormUrls && typeof location.groupFormUrls === 'object'
      ? location.groupFormUrls
      : {};
    for (const [formKey, url] of Object.entries(formUrls)) {
      if (!isPipedriveFormUrl(url) && !isOnSiteGroupInquiryUrl(url)) continue;
      files.push(`group-form-thank-you/${slug}/${formKey}.html`);
    }
  }
  return files;
}

function groupInquiryOutputFiles(locationsDocument) {
  const locations = Array.isArray(locationsDocument.locations) ? locationsDocument.locations : [];
  const files = [];
  for (const location of locations) {
    const formUrls = location.groupFormUrls && typeof location.groupFormUrls === 'object'
      ? location.groupFormUrls
      : {};
    for (const url of Object.values(formUrls)) {
      if (!isOnSiteGroupInquiryUrl(url)) continue;
      files.push(`${url.replace(/^\/+|\/+$/g, '')}.html`);
    }
  }
  return files;
}

const staticOutputFiles = [...new Set(staticAstroRels.map(astroRelToOutputHtml))].sort();

const errors = [];
for (const out of staticOutputFiles) {
  if (specialStaticOutputFiles.has(out)) continue;
  if (!routeOutputs.has(out)) {
    errors.push(`Compiled Astro output "${out}" has no matching routes.json outputFile`);
  }
}

const outputFiles = [...new Set([
  ...staticOutputFiles,
  ...groupFormThankYouOutputFiles(profiledLocationsDocument),
  ...groupInquiryOutputFiles(profiledLocationsDocument),
])].sort();

if (errors.length) {
  console.error('compile-route-artifacts failed:');
  for (const e of errors) console.error(`- ${e}`);
  process.exit(1);
}

const payload = {
  _comment:
    'GENERATED by scripts/compile-route-artifacts.mjs — do not hand-edit paths; run npm run compile:routes',
  outputFiles,
  dynamicLandingModules,
};

function normalizePath(value) {
  const raw = String(value || '').trim();
  if (!raw || raw === '/') return '/';
  const withSlash = raw.startsWith('/') ? raw : `/${raw}`;
  return withSlash.replace(/\/+$/, '') || '/';
}

function compileLocationRouteManifest(registry, locationsDocument) {
  const locations = Array.isArray(locationsDocument.locations) ? locationsDocument.locations : [];
  const locationPaths = locations.map((loc) => normalizePath(`/${loc.slug || loc.id}`));
  const routes = Array.isArray(registry.routes) ? registry.routes : [];
  const aliases = Array.isArray(registry.aliases) ? registry.aliases : [];
  const routeByPath = new Map(routes.map((route) => [normalizePath(route.canonicalPath), route]));
  const locationOwnsPath = (canonicalPath) =>
    locationPaths.some((locationPath) =>
      canonicalPath === locationPath || canonicalPath.startsWith(`${locationPath}/`),
    );

  const locationRouteEntries = locations
    .map((loc) => {
      const canonicalPath = normalizePath(`/${loc.slug || loc.id}`);
      const route = routeByPath.get(canonicalPath);
      if (!route) return null;
        return {
          canonicalPath,
          compatibilitySources: route.locationCompatibilitySources || [],
          externalUrl: loc.externalUrl || route.externalUrl || '',
          officialAlternate: route.locationAlternate || '',
        };
    })
    .filter(Boolean);

  const prefixableCanonicalPaths = routes
    .map((route) => normalizePath(route.canonicalPath))
    .filter((canonicalPath) => canonicalPath !== '/' && !locationOwnsPath(canonicalPath));
  const prefixableTargets = new Set(['/', ...prefixableCanonicalPaths]);
  const prefixableRouteAliases = [];

  for (const route of routes) {
    const canonicalPath = normalizePath(route.canonicalPath);
    if (!prefixableTargets.has(canonicalPath) || canonicalPath === '/') continue;
    for (const source of route.redirectSources || []) {
      prefixableRouteAliases.push([source, canonicalPath]);
    }
  }

  for (const alias of aliases) {
    const target = normalizePath(alias.target);
    if (!prefixableTargets.has(target)) continue;
    prefixableRouteAliases.push([alias.source, target]);
  }

  return {
    locationRouteEntries,
    prefixableCanonicalPaths,
    prefixableRouteAliases,
  };
}

function writeLocationRouteManifest(manifest) {
  const source = [
    '// GENERATED by scripts/compile-route-artifacts.mjs; do not hand-edit.',
    `export const LOCATION_ROUTE_ENTRIES = ${JSON.stringify(manifest.locationRouteEntries, null, 2)};`,
    `export const PREFIXABLE_CANONICAL_PATHS = ${JSON.stringify(manifest.prefixableCanonicalPaths, null, 2)};`,
    `export const PREFIXABLE_ROUTE_ALIASES = ${JSON.stringify(manifest.prefixableRouteAliases, null, 2)};`,
    '',
  ].join('\n');
  fs.mkdirSync(path.dirname(routeManifestPath), { recursive: true });
  fs.writeFileSync(routeManifestPath, source, 'utf8');
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, JSON.stringify(payload, null, 2) + '\n', 'utf8');
writeLocationRouteManifest(compileLocationRouteManifest(registry, profiledLocationsDocument));
console.log(
  `Wrote ${outputFiles.length} static entries + ${dynamicLandingModules.length} dynamic module(s) to ${path.relative(root, outPath)}`,
);
console.log(`Wrote location route manifest to ${path.relative(root, routeManifestPath)}`);
